pub fn search(query: &str) -> Vec<(&'static Page, String)> {
    let needle = query.trim().to_lowercase();
    if needle.is_empty() {
        return vec![];
    }
    let words: Vec<_> = needle.split_whitespace().collect();
    book()
        .pages
        .iter()
        .filter_map(|page| {
            let lower = page.text.to_lowercase();
            if !words.iter().all(|word| lower.contains(word)) {
                return None;
            }
            // Map byte positions through characters, so Tamil and case expansion never
            // become invalid UTF-8 boundaries in a snippet.
            let chars: Vec<char> = page.text.chars().collect();
            let first = lower.find(words[0]).unwrap_or(0);
            let position = lower[..first].chars().count().min(chars.len());
            let start = position.saturating_sub(70);
            let end = (position + 230).min(chars.len());
            Some((
                page,
                format!(
                    "{}{}{}",
                    if start > 0 { "…" } else { "" },
                    chars[start..end].iter().collect::<String>(),
                    if end < chars.len() { "…" } else { "" }
                ),
            ))
        })
        .collect()
}
#[cfg(test)]
mod assurance_tests {
    use super::*;
    #[test]
    fn counts_are_written_with_thousands_separated() {
        assert_eq!(thousands(9), "9");
        assert_eq!(thousands(129), "129");
        assert_eq!(thousands(1673), "1,673");
        assert_eq!(thousands(90187), "90,187");
        assert_eq!(thousands(1234567), "1,234,567");
    }
    #[test]
    fn the_generated_pages_load() {
        let a = assurance();
        assert_eq!(
            a.engine.queries,
            a.engine.cases.iter().map(|c| c.queries).sum::<u32>()
        );
        assert!(!a.limits.chapters.is_empty());
    }
    #[test]
    fn every_reconsider_entry_names_a_chapter_that_exists() {
        let r = reconsider();
        for group in r.conditions.iter().chain(r.costs.iter()) {
            assert!(!group.entries.is_empty(), "{}", group.id);
            for entry in &group.entries {
                assert_eq!(chapter(entry.chapter).number, Some(entry.chapter));
            }
        }
    }
    #[test]
    fn the_design_summary_links_articles_and_chapters_that_exist() {
        let d = design();
        let lines: Vec<_> = d
            .sections
            .iter()
            .flat_map(|s| s.groups.iter())
            .flat_map(|g| g.lines.iter())
            .collect();
        assert!(!lines.is_empty());
        for line in lines {
            assert!(
                articles().articles.iter().any(|a| a.number == line.article),
                "Article {}",
                line.article
            );
            assert_eq!(chapter(line.chapter).number, Some(line.chapter));
        }
    }
}
