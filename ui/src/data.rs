/// Public downloads open on the hosted site from desktop, not its asset server.
pub fn public_url(path: impl AsRef<str>) -> String {
    #[cfg(feature = "desktop")]
    {
        format!("{ORIGIN}{}", path.as_ref())
    }
    #[cfg(not(feature = "desktop"))]
    {
        path.as_ref().into()
    }
}
